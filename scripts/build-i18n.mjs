#!/usr/bin/env node
/**
 * Build public/i18n.js from i18n-src/*.json.
 *
 *   node scripts/build-i18n.mjs            write public/i18n.js
 *   node scripts/build-i18n.mjs --check    exit 1 if public/i18n.js is stale
 *
 * i18n-src/_meta.json holds the language order, native names and locales;
 * each <code>.json holds the full UI dictionary. Every language is merged over
 * the base dictionary (en) so a missing key degrades to English instead of
 * showing a raw key, and this script fails loudly when a dictionary is
 * incomplete so that never has to happen.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'i18n-src');
const OUT = join(ROOT, 'public', 'i18n.js');

const readJson = (name) => JSON.parse(readFileSync(join(SRC, name), 'utf8'));
const meta = readJson('_meta.json');
const base = readJson(`${meta.base}.json`);

const problems = [];

function shape(value, path) {
  if (Array.isArray(value)) return `${path}[](${value.length})`;
  if (value && typeof value === 'object') return `${path}{}`;
  return path;
}

function compare(expected, actual, path, code) {
  if (Array.isArray(expected)) {
    if (!Array.isArray(actual)) return problems.push(`${code}: ${path} should be an array`);
    if (expected.length !== actual.length) problems.push(`${code}: ${path} has ${actual.length} of ${expected.length} items`);
    expected.forEach((item, i) => compare(item, actual[i], `${path}[${i}]`, code));
    return;
  }
  if (expected && typeof expected === 'object') {
    if (!actual || typeof actual !== 'object' || Array.isArray(actual)) return problems.push(`${code}: ${path} should be an object`);
    for (const key of Object.keys(expected)) compare(expected[key], actual[key], path ? `${path}.${key}` : key, code);
    for (const key of Object.keys(actual)) {
      if (!(key in expected)) problems.push(`${code}: unexpected key ${path ? `${path}.${key}` : key}`);
    }
    return;
  }
  if (typeof actual !== 'string' || !actual.trim()) problems.push(`${code}: ${path} is empty or not a string`);
}

const languages = [];
const strings = {};

for (const lang of meta.order) {
  const file = `${lang.code}.json`;
  let dict;
  try {
    dict = readJson(file);
  } catch (err) {
    problems.push(`${lang.code}: cannot read i18n-src/${file} (${err.message})`);
    continue;
  }
  compare(base, dict, '', lang.code);
  languages.push({
    code: lang.code,
    native: lang.native,
    english: lang.english,
    locale: lang.locale,
    ...(lang.dir ? { dir: lang.dir } : {})
  });
  // Merge over the base so a partially translated language still renders.
  strings[lang.code] = deepMerge(base, dict);
}

// Catch stray dictionaries that _meta.json does not list.
for (const file of readdirSync(SRC)) {
  if (!file.endsWith('.json') || file === '_meta.json') continue;
  const code = file.slice(0, -5);
  if (code !== meta.base && !meta.order.some((l) => l.code === code)) problems.push(`i18n-src/${file} is not listed in _meta.json order`);
}

function deepMerge(baseValue, override) {
  if (Array.isArray(baseValue)) return Array.isArray(override) ? override : baseValue;
  if (baseValue && typeof baseValue === 'object') {
    const out = {};
    for (const key of Object.keys(baseValue)) out[key] = deepMerge(baseValue[key], override && override[key]);
    return out;
  }
  return typeof override === 'string' && override.trim() ? override : baseValue;
}

if (problems.length) {
  console.error(`i18n dictionaries: ${problems.length} problem(s)`);
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

const bundle = `/* WIMP — language pack. Generated by scripts/build-i18n.mjs from i18n-src/*.json.
   Do not edit by hand: edit i18n-src/<code>.json and run "npm run i18n". */
window.WIMP_I18N = ${JSON.stringify({ base: meta.base, default: meta.default, aliases: meta.aliases, languages, strings }, null, 1)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    console.error('public/i18n.js is missing — run "npm run i18n"');
    process.exit(1);
  }
  if (current !== bundle) {
    console.error('public/i18n.js is stale — run "npm run i18n"');
    process.exit(1);
  }
  console.log(`public/i18n.js is up to date (${languages.length} languages)`);
  process.exit(0);
}

writeFileSync(OUT, bundle);
const kb = (Buffer.byteLength(bundle) / 1024).toFixed(0);
console.log(`public/i18n.js written: ${languages.length} languages, ${kb} KB`);
